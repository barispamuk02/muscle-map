function getCustomExerciseTranslation(muscleId, group, idx) {
    if (typeof currentLang === 'undefined' || currentLang === 'ru') return null;
    if (typeof customExercisesTranslations === 'undefined') return null;
    if (!customExercisesTranslations.en) return null;
    
    const muscleGroup = customExercisesTranslations.en[muscleId];
    if (!muscleGroup) return null;
    
    const arr = muscleGroup[group]; // 'primary' или 'secondary'
    if (!arr || !Array.isArray(arr)) return null;
    
    return arr.find(item => item.idx === idx) || null;
}

function translateCustomExercise(ex) {
    if (!ex || !ex.isCustom) return ex;
    
    const tr = getCustomExerciseTranslation(ex.muscleId, ex.customGroup, ex.customIdx);
    if (!tr) return ex;
    
    return {
        ...ex,
        name: tr.name || ex.name,
        description: tr.description || ex.description
    };
}

function getExerciseNameUniversal(ex) {
    if (ex.isCustom) {
        return translateCustomExercise(ex).name;
    }
    if (typeof translateExerciseName === 'function') {
        return translateExerciseName(ex);
    }
    return ex.name || ex.name_en || '';
}

function getExerciseDescriptionUniversal(ex) {
    if (ex.isCustom) {
        return translateCustomExercise(ex).description || ex.description || '';
    }
    if (typeof translateExerciseDescription === 'function') {
        return translateExerciseDescription(ex) || ex.description || '';
    }
    return ex.description || '';
}


