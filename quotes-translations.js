function getQuoteTranslation(index) {
    if (currentLang === 'ru') return null;
    if (!quotesTranslations || !quotesTranslations.en) return null;
    return quotesTranslations.en[index] || null;
}

function getQuoteOfDayTranslated() {
    const now = new Date();
    const start = new Date(now.getFullYear(), 0, 0);
    const diff = now - start;
    const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));
    const index = dayOfYear % motivationalQuotes.length;
    
    const ruQuote = motivationalQuotes[index];
    if (currentLang === 'ru') return ruQuote;
    
    const enQuote = getQuoteTranslation(index);
    return enQuote || ruQuote; // fallback на RU, если EN не найден
}